"""Make logo.h (the splash logo) from skn_logo.jpg.

    python make_logo.py

The logo is yellow on black, so it is kept as 4-bit intensity (0 = black,
15 = the logo's yellow), two pixels a byte, high nibble first: smooth edges
for half the flash of RGB565. One size per screen (FPV_SCREEN_480 or not).
The jpg itself is not in the repository; logo.h is.
"""
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SIZES = {"1": 232, "0": 168}      # FPV_SCREEN_480 -> logo height in pixels


def level(rgb):
    # yellow (239, 234, 102) -> 15, black -> 0, by red + green
    v = (rgb[0] + rgb[1]) / (239 + 234)
    return max(0, min(15, round(v * 15)))


def main():
    src = Image.open(HERE / "skn_logo.jpg").convert("RGB")
    out = ["/* Generated by make_logo.py from skn_logo.jpg - do not edit. */",
           "#pragma once", "#include <stdint.h>", ""]
    for i, (big, h) in enumerate(SIZES.items()):
        w = round(src.width * h / src.height) & ~1
        img = src.resize((w, h), Image.LANCZOS)
        px = [level(p) for p in img.getdata()]
        data = bytes((px[j] << 4) | px[j + 1] for j in range(0, len(px), 2))
        out.append(("#if" if i == 0 else "#else") + (" FPV_SCREEN_480" if i == 0 else ""))
        out.append(f"constexpr int LOGO_W = {w}, LOGO_H = {h};")
        out.append("static const uint8_t LOGO[] = {")
        for j in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[j:j + 24]) + ",")
        out.append("};")
    out += ["#endif", "constexpr uint32_t LOGO_RGB = 0xefea66;   /* the logo's yellow */", ""]
    (HERE.parent / "logo.h").write_bytes("\n".join(out).encode())


if __name__ == "__main__":
    main()
